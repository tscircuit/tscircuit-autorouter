// The snapshot intentionally records the failing output for review, not a fix.
test("Key Finder repro: GND via overlaps unconnected U1 pin58/P1_03", async (): Promise<void> => {
  const solver = new AutoroutingPipelineSolver9_PreloadedTraceGraph(
    structuredClone(input),
    { cacheProvider: null },
  )
  solver.solve()
  expect(solver.solved).toBe(true)
  expect(solver.failed).toBe(false)
  const traces = solver.getOutputSimplifiedPcbTraces()
  const pad = input.obstacles.find(
    (obstacle) => obstacle.circuitJsonMetadata?.pcb_port_id === "pcb_port_57",
  )!
  expect(pad.circuitJsonMetadata?.source_port_name).toBe("P1_03")
  expect(pad.connectedTo).not.toContain("source_net_1") // GND
  const groundPad = input.obstacles.find(
    (obstacle) => obstacle.circuitJsonMetadata?.pcb_port_id === "pcb_port_20",
  )!
  const candidates = traces
    .filter(
      (trace) =>
        trace.connection_name === "source_net_1" ||
        trace.pcb_trace_id.startsWith("source_net_1_mst"),
    )
    .flatMap((trace) => trace.route)
    .filter((point) => point.route_type === "via")
    .filter((point) => point.from_layer === "top" || point.to_layer === "top")
    .map((via) => ({
      via,
      gap:
        Math.hypot(
          Math.max(Math.abs(via.x - pad.center.x) - pad.width / 2, 0),
          Math.max(Math.abs(via.y - pad.center.y) - pad.height / 2, 0),
        ) -
        (via.via_diameter ?? input.minViaPadDiameter!) / 2,
    }))
    .sort((a, b) => a.gap - b.gap)
  expect(candidates.length).toBeGreaterThan(0)
  const { via, gap } = candidates[0]!
  // Like the other repro tests, assert the current incorrect behavior so a
  // later routing fix must deliberately update this baseline.
  expect(gap).toBeLessThan(0)
  expect(gap).toBeCloseTo(-0.024843453046, 6)

  // Render an isolated detail from the actual obstacle and route records.
  // This only filters the drawing; the solver above still receives the full
  // board input, because removing unrelated nets changes the route.
  const detail = convertSrjToGraphicsObject({
    ...input,
    connections: [],
    obstacles: [pad, groundPad],
    traces: [
      {
        type: "pcb_trace",
        pcb_trace_id: "detail-ground-via",
        connection_name: "source_net_1",
        route: [via],
      },
    ],
  })
  const closeUp = getGraphicsSvgFrames({
    frames: [
      {
        name: `GND via / pin58: ${(-gap).toFixed(4)}mm overlap`,
        pipeline: "end",
        iteration: solver.iterations,
        graphics: {
          ...detail,
          texts: [
            {
              x: pad.center.x + 0.5,
              y: pad.center.y,
              text: "pin58 / P1_03 (NC)",
              fontSize: 0.09,
              anchorSide: "center_left",
            },
            {
              x: via.x + 0.5,
              y: via.y,
              text: "GND via",
              fontSize: 0.09,
              anchorSide: "center_left",
            },
            {
              x: groundPad.center.x + 0.5,
              y: groundPad.center.y,
              text: "pin21 / GND",
              fontSize: 0.09,
              anchorSide: "center_left",
            },
          ],
        },
        layer: 0,
      },
    ],
    cellWidth: 2.6,
    cellHeight: 1.6,
    backgroundColor: "white",
  })
  // Full-board panel uses the repository's standard relaxed-DRC evaluator.
  // The detail reports geometric copper overlap, independent of DRC policy.
  const board = getBugReportSnapshotSvg({
    inputSrj: input,
    srjWithPointPairs: solver.srjWithPointPairs!,
    routedTraces: traces,
  })
  await expect(
    stackSvgsHorizontally([board, closeUp], { gap: 20 }),
  ).toMatchSvgSnapshot(import.meta.path)
})
