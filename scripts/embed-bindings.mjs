import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const root = new URL("../", import.meta.url)
const output = new URL("lib/bindings/generated/", root)
mkdirSync(output, { recursive: true })

for (const [name, packageName, binaryName] of [
  ["autorouter", "autorouter-bindings", "autorouter_bindings"],
  ["tinyHypergraph", "tiny-hypergraph-bindings", "tiny_hypergraph_bindings"],
]) {
  const binary = readFileSync(new URL(`rust/${packageName}/pkg/${binaryName}_bg.wasm`, root))
  if (!binary.subarray(0, 8).equals(Buffer.from([0, 97, 115, 109, 1, 0, 0, 0]))) {
    throw new Error(`Invalid WASM binary for ${packageName}`)
  }
  const target = new URL(`${name}Module.ts`, output)
  writeFileSync(target, `// Generated by scripts/embed-bindings.mjs.\nexport const wasmBase64 = ${JSON.stringify(binary.toString("base64"))}\n`)
  console.log(`Embedded ${binary.length} bytes in ${fileURLToPath(target)}`)
}
