import { execFileSync } from "node:child_process"
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const root = new URL("../", import.meta.url)
const bindgen = process.env.WASM_BINDGEN ?? "wasm-bindgen"
const installed = execFileSync(bindgen, ["--version"], {
  encoding: "utf8",
}).trim()
const output = new URL("lib/bindings/generated/", root)
mkdirSync(output, { recursive: true })

for (const [name, packageName, binaryName] of [
  ["tinyHypergraph", "tiny-hypergraph-bindings", "tiny_hypergraph_bindings"],
  [
    "autorouter",
    "capacity-autorouter-bindings",
    "capacity_autorouter_bindings",
  ],
]) {
  const crate = fileURLToPath(new URL(`rust/${packageName}/`, root))
  const lockfile = readFileSync(`${crate}Cargo.lock`, "utf8")
  const version = lockfile.match(
    /name = "wasm-bindgen"\nversion = "([^"]+)"/,
  )?.[1]
  if (!version)
    throw new Error(`${packageName}/Cargo.lock does not pin wasm-bindgen`)
  if (installed !== `wasm-bindgen ${version}`) {
    throw new Error(
      `Expected wasm-bindgen ${version}; run cargo install wasm-bindgen-cli --version ${version} --locked`,
    )
  }
  execFileSync(
    "cargo",
    [
      "build",
      "--manifest-path",
      `${crate}Cargo.toml`,
      "--target-dir",
      `${crate}target`,
      "--locked",
      "--target",
      "wasm32-unknown-unknown",
      "--release",
    ],
    { stdio: "inherit" },
  )
  execFileSync(
    bindgen,
    [
      `${crate}target/wasm32-unknown-unknown/release/${binaryName}.wasm`,
      "--target",
      "web",
      "--typescript",
      "--out-dir",
      `${crate}pkg`,
    ],
    { stdio: "inherit" },
  )
  const binary = readFileSync(
    new URL(`rust/${packageName}/pkg/${binaryName}_bg.wasm`, root),
  )
  if (
    !binary.subarray(0, 8).equals(Buffer.from([0, 97, 115, 109, 1, 0, 0, 0]))
  ) {
    throw new Error(`Invalid WASM binary for ${packageName}`)
  }
  const target = new URL(`${name}Module.ts`, output)
  writeFileSync(
    target,
    `// Generated by scripts/build-bindings.mjs.\nexport const wasmBase64 = ${JSON.stringify(binary.toString("base64"))}\n`,
  )
  console.log(`Embedded ${binary.length} bytes in ${fileURLToPath(target)}`)
}
