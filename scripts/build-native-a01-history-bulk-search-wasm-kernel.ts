import { createHash } from "node:crypto"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

// Ordinary builds consume the checked-in bytes and need no C compiler.
// Set NATIVE_A01_HISTORY_BULK_SEARCH_WASM_CLANG to an LLVM clang executable to regenerate.
const directory = fileURLToPath(new URL(
  "../lib/autorouter-pipelines/AutoroutingPipeline9_Parallel/native-a01-history-bulk-search/",
  import.meta.url,
))
const source = join(directory, "historySearchKernel.c")
const temporary = mkdtempSync(join(tmpdir(), "native-a01-history-bulk-search-build-"))
const output = join(temporary, "historySearchKernel.wasm")
const compiler = process.env.NATIVE_A01_HISTORY_BULK_SEARCH_WASM_CLANG ?? "clang"
const flags = [
  "--target=wasm32-unknown-unknown", "-mcpu=mvp", "-O3",
  "-fno-fast-math", "-ffp-contract=off", "-fno-associative-math",
  "-fno-reciprocal-math", "-fsigned-zeros", "-fno-finite-math-only",
  "-fno-math-errno", "-fdenormal-fp-math=ieee", "-ffreestanding",
  "-fno-builtin", "-fno-vectorize", "-fno-slp-vectorize", "-mno-simd128",
  "-mno-relaxed-simd", "-nostdlib", "-Wl,--no-entry",
  "-Wl,--export-memory", "-Wl,--export=__heap_base",
  "-Wl,--export=configure", "-Wl,--export=run", "-Wl,--strip-all", "-Wl,--allow-undefined",
]
try {
  const result = Bun.spawnSync([compiler, ...flags, "-o", output, source])
  if (result.exitCode !== 0) throw new Error(new TextDecoder().decode(result.stderr))
  const bytes = readFileSync(output)
  const imports = WebAssembly.Module.imports(new WebAssembly.Module(new Uint8Array(bytes)))
  if (imports.length !== 1 || imports[0]!.module !== "history" || imports[0]!.name !== "shouldContinue" || imports[0]!.kind !== "function") {
    throw new Error("Native A01 history search kernel introduced an unexpected runtime import")
  }
  const version = Bun.spawnSync([compiler, "--version"])
  const provenance = new TextDecoder().decode(version.stdout).split("\n")[0]!
  const sourceHash = createHash("sha256").update(new Uint8Array(readFileSync(source))).digest("hex")
  const wasmHash = createHash("sha256").update(new Uint8Array(bytes)).digest("hex")
  const rows: string[] = []
  for (let index = 0; index < bytes.length; index += 32) {
    rows.push(`  ${[...bytes.subarray(index, index + 32)].join(", ")},`)
  }
  writeFileSync(join(directory, "historySearchKernelBytes.ts"),
    `// Generated by scripts/build-native-a01-history-bulk-search-wasm-kernel.ts; do not edit.\n` +
    `// ${provenance}\n// Strict compiler flags: ${flags.join(" ")}\n` +
    `export const nativeA01HistoryBulkSearchKernelSourceSha256 = "${sourceHash}"\n` +
    `export const nativeA01HistoryBulkSearchKernelWasmSha256 = "${wasmHash}"\n` +
    `export const historySearchKernelBytes = new Uint8Array([\n${rows.join("\n")}\n])\n`)
} finally {
  rmSync(temporary, { recursive: true, force: true })
}
