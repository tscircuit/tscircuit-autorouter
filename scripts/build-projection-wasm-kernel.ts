import { createHash } from "node:crypto"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

// LLVM clang 22.1.8 generated the checked-in bytes. Ordinary builds require no C
// compiler. Set PROJECTION_WASM_CLANG to an LLVM clang executable to regenerate.
const directory = fileURLToPath(new URL(
  "../lib/autorouter-pipelines/AutoroutingPipeline9_Parallel/repair04/projectionWasm/",
  import.meta.url,
))
const source = join(directory, "projectionKernel.c")
const temporary = mkdtempSync(join(tmpdir(), "projection-wasm-build-"))
const output = join(temporary, "projectionKernel.wasm")
const compiler = process.env.PROJECTION_WASM_CLANG ?? "clang"
const flags = [
  "--target=wasm32-unknown-unknown", "-mcpu=mvp", "-O3",
  "-fno-fast-math", "-ffp-contract=off", "-fno-associative-math",
  "-fno-reciprocal-math", "-fsigned-zeros", "-fno-finite-math-only",
  "-fno-math-errno", "-fdenormal-fp-math=ieee", "-ffreestanding",
  "-fno-builtin", "-fno-vectorize", "-fno-slp-vectorize", "-mno-simd128",
  "-mno-relaxed-simd", "-nostdlib", "-Wl,--no-entry",
  "-Wl,--export-memory", "-Wl,--export=__heap_base",
  "-Wl,--allow-undefined", "-Wl,--strip-all",
]
try {
  const result = Bun.spawnSync([compiler, ...flags, "-o", output, source])
  if (result.exitCode !== 0)
    throw new Error(new TextDecoder().decode(result.stderr))
  const bytes = readFileSync(output)
  const imports = WebAssembly.Module.imports(new WebAssembly.Module(new Uint8Array(bytes)))
  if (imports.length !== 1 || imports[0]!.module !== "env" ||
    imports[0]!.name !== "guard_vertex" || imports[0]!.kind !== "function")
    throw new Error("Projection kernel introduced an unexpected runtime import")
  const version = Bun.spawnSync([compiler, "--version"])
  const provenance = new TextDecoder().decode(version.stdout).split("\n")[0]!
  const sourceHash = createHash("sha256").update(new Uint8Array(readFileSync(source))).digest("hex")
  const wasmHash = createHash("sha256").update(new Uint8Array(bytes)).digest("hex")
  const rows: string[] = []
  for (let index = 0; index < bytes.length; index += 32)
    rows.push(`  ${[...bytes.subarray(index, index + 32)].join(", ")},`)
  writeFileSync(join(directory, "projectionKernelBytes.ts"),
    `// Generated by scripts/build-projection-wasm-kernel.ts; do not edit.\n` +
    `// ${provenance}\n// Strict compiler flags: ${flags.join(" ")}\n` +
    `export const projectionKernelSourceSha256 = "${sourceHash}"\n` +
    `export const projectionKernelWasmSha256 = "${wasmHash}"\n` +
    `export const projectionKernelBytes = new Uint8Array([\n${rows.join("\n")}\n])\n`)
} finally {
  rmSync(temporary, { recursive: true, force: true })
}
