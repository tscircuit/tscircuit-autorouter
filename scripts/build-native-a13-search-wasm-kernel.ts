import { createHash } from "node:crypto"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

// Normal builds use the checked-in module; LLVM is only needed to regenerate.
const directory = fileURLToPath(new URL("../lib/autorouter-pipelines/AutoroutingPipeline9_Parallel/a13-search-wasm/", import.meta.url))
const source = join(directory, "kernel.c")
const temporary = mkdtempSync(join(tmpdir(), "native-a13-search-wasm-"))
const output = join(temporary, "kernel.wasm")
const compiler = process.env.NATIVE_A13_SEARCH_WASM_CLANG ?? "clang"
const flags = ["--target=wasm32", "-O3", "-msimd128", "-fno-fast-math", "-ffp-contract=off",
  "-fno-associative-math", "-fno-reciprocal-math", "-fsigned-zeros", "-fno-finite-math-only", "-nostdlib",
  "-Wl,--no-entry", "-Wl,--export=configure", "-Wl,--export=begin_search", "-Wl,--export=run",
  "-Wl,--export=get_expansions", "-Wl,--export=get_pops", "-Wl,--export=set_heap_capacity", "-Wl,--export=__heap_base"]
try {
  const result = Bun.spawnSync([compiler, ...flags, source, "-o", output])
  if (result.exitCode !== 0) throw new Error(new TextDecoder().decode(result.stderr))
  const bytes = new Uint8Array(readFileSync(output))
  if (WebAssembly.Module.imports(new WebAssembly.Module(bytes)).length !== 0) throw new Error("Native A13 kernel has unexpected imports")
  const version = new TextDecoder().decode(Bun.spawnSync([compiler, "--version"]).stdout).split("\n")[0]!
  const sourceHash = createHash("sha256").update(new Uint8Array(readFileSync(source))).digest("hex")
  const binaryHash = createHash("sha256").update(bytes).digest("hex")
  writeFileSync(join(directory, "kernelBytes.ts"), `// Generated by scripts/build-native-a13-search-wasm-kernel.ts.\n` +
    `// ${version}\n// Strict flags: ${flags.join(" ")}\n` +
    `// Source SHA256: ${sourceHash}\n// Module SHA256: ${binaryHash}\n` +
    `export const kernelBase64 =\n  "${Buffer.from(bytes).toString("base64")}"\n`)
} finally { rmSync(temporary, { recursive: true, force: true }) }
